<section class="policy-body">
  <article>
    <h2>هدف محتوا</h2>
    <p>مقالات و صفحات خدمات با هدف توضیح روشن موضوعات پزشکی، محدودیت شواهد، مسیر ارزیابی و انتظارات واقع‌بینانه تهیه می‌شوند. در موضوعات بازساختی و ارتوبیولوژیک از ادعاهای قطعی، وعده درمان تضمینی و تعمیم نتایج پژوهش‌های اولیه به همه بیماران پرهیز می‌شود.</p>
  </article>

  <article>
    <h2>منابع و شواهد</h2>
    <p>در تدوین مطالب از منابع علمی معتبر، مرورهای نظام‌مند، راهنماهای بالینی و مطالعات انسانی مرتبط استفاده می‌شود. سطح شواهد در کاربردهای مختلف یکسان نیست و این تفاوت باید در متن منعکس شود.</p>
  </article>

  <article>
    <h2>بازبینی و به‌روزرسانی</h2>
    <p>مطالب در صورت تغییر مهم شواهد، راهنماهای بالینی، پروتکل‌های داخلی یا اطلاعات خدمات بازبینی می‌شوند. تاریخ آخرین به‌روزرسانی در مقالات ثبت می‌شود تا خواننده بداند چه زمانی متن اصلاح شده است.</p>
  </article>

  <article>
    <h2>تعارض منافع و شفافیت</h2>
    <p>وجود یک درمان یا فناوری در کلینیک به معنی مناسب بودن آن برای همه بیماران نیست. صفحات سایت باید بین توضیح علمی، معرفی خدمت و تبلیغ تفاوت قائل شوند و محدودیت‌ها، موارد عدم‌تناسب و نیاز به ارزیابی پزشکی را صریح بیان کنند.</p>
  </article>

  <article>
    <h2>اصلاح خطا</h2>
    <p>اگر خطای علمی، اطلاعات منسوخ یا عبارت مبهمی شناسایی شود، متن اصلاح و در صورت لزوم تاریخ به‌روزرسانی ثبت می‌شود. هدف، حفظ نسخه‌ای دقیق‌تر و قابل دفاع از محتواست، نه انباشتن متن صرفاً برای موتور جست‌وجو.</p>
  </article>

  <article>
    <h2>مرز اطلاعات عمومی و درمان فردی</h2>
    <p>هیچ صفحه‌ای در سایت جایگزین ارزیابی اختصاصی بیمار نیست. علائم مشابه می‌توانند علت‌های متفاوت داشته باشند و انتخاب درمان باید بر پایه شرح حال، معاینه، تصویربرداری، آزمایش‌ها و شرایط فردی انجام شود.</p>
  </article>
